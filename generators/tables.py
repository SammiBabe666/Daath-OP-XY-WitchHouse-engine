"""Generates tables.h for Daath. Run from the repository root:
    python generators/tables.py > tables.h
"""
import math

SINE = 1024     # sub oscillator: Q15 sine, no interpolation (residual below -50 dB)
CLIP = 4096     # Hex soft clip over [-2, 2), Q15 at half scale, looked up directly
ONE = 1 << 27


def clip(v):
    v = max(-1.5, min(1.5, v))
    return v - 4 * v ** 3 / 27


print('// Generated by generators/tables.py; do not edit.')
print('#pragma once')
print('#include <opxy/types.hpp>')
print('namespace daath {')
print('// One cycle of sine, Q15, %d points.' % SINE)
print('const opxy::i16 sub_sine[%d] = {' % SINE)
values = [round(32767 * math.sin(2 * math.pi * i / SINE)) for i in range(SINE)]
for i in range(0, SINE, 16):
    print('    ' + ', '.join(str(v) for v in values[i:i + 16]) + ',')
print('};')
print('// Hex soft clip at half scale: (x - 4x^3/27) / 2 over [-1.5, 1.5], flat beyond.')
print('// Index (x + 2) * 1024 for x in [-2, 2); Q15, scaled to Q27 by 4096 when read.')
print('// The half leaves the DC blocker room for its overshoot.')
print('const opxy::i16 hex_curve[%d] = {' % CLIP)
values = [round(32768 / 2 * clip(-2 + 4 * (i + 0.5) / CLIP)) for i in range(CLIP)]
for i in range(0, CLIP, 16):
    print('    ' + ', '.join(str(v) for v in values[i:i + 16]) + ',')
print('};')
print('}')
